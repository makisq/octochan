// Команда ochan — утилита сравнения и применения конфигураций.
//
// Прежний main делал три лишние вещи:
//   - перехватывал "|" в аргументах и перезапускал сам себя подпроцессом,
//     хотя конвейеры и так собирает оболочка;
//   - уходил в интерактивный режим, если хоть один аргумент содержал "/",
//     из-за чего `ochan diff ./a.conf ./b.conf` не выполнял сравнение;
//   - поднимал второй наблюдатель за модулями, дублируя тот, что живёт в cmd.
package main

import (
	"os"

	"octochan/cmd"
	"octochan/sandbox"

	// Регистрация источника «живой PostgreSQL» (схема postgres://).
	_ "octochan/pgsource"
)

func main() {
	// Процесс песочницы ставит ограничения ядра раньше всего остального:
	// ни конфига, ни журнала, ни модулей он не читает.
	if sandbox.Enter() {
		os.Exit(cmd.SandboxChild())
	}
	os.Exit(cmd.Execute())
}
