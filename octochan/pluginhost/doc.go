// Package pluginhost — хост подключаемых модулей.
//
// Модуль это отдельный исполняемый файл, который общается с октоханом
// по gRPC через hashicorp/go-plugin и приносит то, что объявит: команды,
// языки, исполнителей сценариев. Пакет отвечает за запуск, проверку
// контрольной суммы, взаимный TLS, перенос описаний команд cobra через
// protobuf в обе стороны и вызовы исполнителей.
//
// Имя pluginhost, а не plugin, чтобы не конфликтовать с пакетом
// hashicorp/go-plugin, который здесь же и импортируется.
//
// Пакет не зависит ни от config, ни от rlm, ни от scenario: исполнителей он
// переносит JSON-ом, а типизирует их мост runnerhost.
package pluginhost
