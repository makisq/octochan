param([string]$Out)
# Снимает «форму» печатных символов ASCII: долю закрашенных пикселей в
# каждой ячейке сетки 4×8 внутри знакоместа. Форма усредняется по
# нескольким моноширинным шрифтам, чтобы не подстраиваться под один.
Add-Type -AssemblyName System.Drawing

$cols = 4; $rows = 8
$chars = ' .,:;''`"^-_~=+*<>!|/\()[]{}ilIjJ1tfrcvunxzoaedbqpgyYPTVLCOQ0U8&%#$@MWHNKARSXZ'

$installed = (New-Object System.Drawing.Text.InstalledFontCollection).Families | ForEach-Object { $_.Name }
$fonts = @("Consolas", "Cascadia Mono", "DejaVu Sans Mono", "Lucida Console", "Courier New") | Where-Object { $installed -contains $_ }
"шрифты: " + ($fonts -join ", ")

$sum = @{}
foreach ($ch in $chars.ToCharArray()) { $sum[[string]$ch] = New-Object double[] ($cols * $rows) }

foreach ($name in $fonts) {
  $font = New-Object System.Drawing.Font($name, 48, [System.Drawing.GraphicsUnit]::Pixel)
  $probe = New-Object System.Drawing.Bitmap(10, 10)
  $g0 = [System.Drawing.Graphics]::FromImage($probe)
  $fmt = [System.Drawing.StringFormat]::GenericTypographic
  $cellW = [int][Math]::Round($g0.MeasureString("M", $font, 1000, $fmt).Width)
  $cellH = [int][Math]::Round($font.GetHeight($g0))
  $g0.Dispose(); $probe.Dispose()

  foreach ($ch in $chars.ToCharArray()) {
    $bmp = New-Object System.Drawing.Bitmap($cellW, $cellH)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::Black)
    $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAlias
    $g.DrawString([string]$ch, $font, [System.Drawing.Brushes]::White, 0, 0, $fmt)
    $g.Dispose()
    $vec = $sum[[string]$ch]
    for ($cy = 0; $cy -lt $rows; $cy++) {
      for ($cx = 0; $cx -lt $cols; $cx++) {
        $x0 = [int]($cx * $cellW / $cols); $x1 = [int](($cx + 1) * $cellW / $cols)
        $y0 = [int]($cy * $cellH / $rows); $y1 = [int](($cy + 1) * $cellH / $rows)
        $acc = 0.0; $n = 0
        for ($y = $y0; $y -lt $y1; $y++) { for ($x = $x0; $x -lt $x1; $x++) { $acc += $bmp.GetPixel($x, $y).R / 255.0; $n++ } }
        $vec[$cy * $cols + $cx] += $acc / [Math]::Max(1, $n)
      }
    }
    $bmp.Dispose()
  }
  $font.Dispose()
  "  {0}: знакоместо {1}x{2}" -f $name, $cellW, $cellH
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Code generated by tools/logogen/glyphs.ps1; DO NOT EDIT.")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("package main")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("// Форма символов: доля закрашенных пикселей в ячейках сетки")
[void]$sb.AppendLine("// glyphCols×glyphRows, усреднённая по шрифтам: " + ($fonts -join ", ") + ".")
[void]$sb.AppendLine("const (")
[void]$sb.AppendLine("`tglyphCols = $cols")
[void]$sb.AppendLine("`tglyphRows = $rows")
[void]$sb.AppendLine(")")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("var glyphShapes = map[byte][glyphCols * glyphRows]float64{")
foreach ($ch in $chars.ToCharArray()) {
  $vals = $sum[[string]$ch] | ForEach-Object { ($_ / $fonts.Count).ToString("0.000", [Globalization.CultureInfo]::InvariantCulture) }
  $lit = switch ([string]$ch) { "'" { "'\''" } "\" { "'\\'" } default { "'$ch'" } }
  [void]$sb.AppendLine("`t" + $lit + ": {" + ($vals -join ", ") + "},")
}
[void]$sb.AppendLine("}")
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
"записано: $Out, символов: $($chars.Length)"
